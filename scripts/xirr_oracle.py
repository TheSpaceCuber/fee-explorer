"""Generate tests/fixtures/xirr-oracle.json: expected IRRs from an independent XIRR implementation.

Why: XIRR is easy to get subtly wrong (day counts, convergence, sign handling). pyxirr is a
widely used implementation that matches Excel's XIRR, so if our TS engine agrees with it to
~1e-8 on many cash-flow shapes, we can trust ours.

The flows for hand-worked cases are built from the fixture's EXPECTED values, not from the
engine's output. That keeps the oracle independent of the code under test.

Usage:
    python -m venv .venv
    .venv/Scripts/pip install pyxirr        (Windows; on macOS/Linux: .venv/bin/pip)
    .venv/Scripts/python scripts/xirr_oracle.py
"""

from __future__ import annotations

import json
from datetime import date
from pathlib import Path

from pyxirr import xirr

ROOT = Path(__file__).resolve().parent.parent
FIXTURES = ROOT / "tests" / "fixtures"


def lp_flows_for_case(case: dict) -> list[tuple[str, float]]:
    """LP view: calls are negative, expected LP distributions positive, NAV positive at the end."""
    expected_lp_by_event: dict[str, float] = {}
    for row in case["expected"]["allocations"]:
        expected_lp_by_event[row["eventId"]] = expected_lp_by_event.get(row["eventId"], 0.0) + row["lp"]

    flows: list[tuple[str, float]] = []
    for e in case["events"]:
        if e["kind"] == "capital_call":
            flows.append((e["date"], -(e["investment"] + e["fee"])))
        else:
            flows.append((e["date"], expected_lp_by_event.get(e["id"], 0.0)))
    nav = case.get("nav")
    if nav and nav["amount"] > 0:
        flows.append((nav["date"], nav["amount"]))
    return flows


# Extra cash-flow shapes that stress XIRR itself (not the waterfall).
GENERIC: list[dict] = [
    {"id": "G1-simple-double", "flows": [("2020-01-01", -100), ("2025-01-01", 200)]},
    {"id": "G2-loss", "flows": [("2020-01-01", -100), ("2023-06-30", 40)]},
    {"id": "G3-short-high", "flows": [("2024-01-01", -100), ("2024-02-15", 180)]},
    {"id": "G4-leap-span", "flows": [("2024-02-28", -100), ("2024-03-01", -50), ("2028-02-29", 260)]},
    {
        "id": "G5-pe-jcurve",
        "flows": [
            ("2018-03-31", -25), ("2018-09-30", -20), ("2019-06-30", -30), ("2020-03-31", -15),
            ("2021-06-30", 10), ("2022-12-31", 35), ("2023-09-30", 60), ("2025-03-31", 55),
        ],
    },
    {
        "id": "G6-mixed-signs",
        "flows": [
            ("2019-01-01", -100), ("2019-07-01", 20), ("2020-01-01", -50),
            ("2021-01-01", 30), ("2023-01-01", 150),
        ],
    },
    {"id": "G7-near-zero", "flows": [("2020-01-01", -100), ("2021-01-01", 100.0001)]},
]


def irr_of(flows: list[tuple[str, float]]) -> float:
    dates = [date.fromisoformat(d) for d, _ in flows]
    amounts = [a for _, a in flows]
    return float(xirr(dates, amounts))


def main() -> None:
    hand = json.loads((FIXTURES / "hand-worked.json").read_text(encoding="utf-8"))
    cases = []
    for case in hand["cases"]:
        if "expected" not in case:
            continue
        flows = lp_flows_for_case(case)
        cases.append({"id": case["id"], "flows": [{"date": d, "amount": a} for d, a in flows], "irr": irr_of(flows)})

    generic = [
        {"id": g["id"], "flows": [{"date": d, "amount": a} for d, a in g["flows"]], "irr": irr_of(g["flows"])}
        for g in GENERIC
    ]

    out = {
        "description": "Generated by scripts/xirr_oracle.py using pyxirr. Do not edit by hand.",
        "cases": cases,
        "generic": generic,
    }
    (FIXTURES / "xirr-oracle.json").write_text(json.dumps(out, indent=2) + "\n", encoding="utf-8")
    print(f"Wrote {len(cases)} hand-worked + {len(generic)} generic IRRs")


if __name__ == "__main__":
    main()
